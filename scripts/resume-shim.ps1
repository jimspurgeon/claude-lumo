# resume-shim.ps1 - Resume-aware launcher for claude-lumo (Windows PowerShell)
# Source this file from your PowerShell profile to enable it (see "Resume shim" in the README).
#
# Purpose: a tool (like Orca) resumes sessions with a plain `claude --resume <id>`. When the
# resumed session's transcript used a lumo-* model, re-launch it through claude-lumo with the
# same arguments; otherwise run the real claude.exe unchanged (same args, exit code, output).
# Bare `claude -r` / `claude --resume` (no id) opens the resume-picker helper instead, so the
# engine is picked before Claude Code's own (too-late-to-reroute) session picker runs.
# Do not edit this file: it belongs to the claude-lumo repo and updates overwrite it.
#
# Transcript search order (first hit wins; the id lives under projects/<munged-path>/):
#   1. $env:CLAUDE_CONFIG_DIR if set
#   2. ~/.claude (shared mode)
#   3. ~/.claude-lumo/config (the separated Lumo data store, when data separation is on)

# Resolve the picker helper next to this shim (~/.claude/lumo is a junction to the repo, so
# dot-sourcing ~/.claude/lumo/scripts/resume-shim.ps1 finds the repo's picker after updates).
$resumePickerPs1 = Join-Path $PSScriptRoot 'resume-picker.ps1'

function claude {
    $id = $null
    $bare = $false
    for ($i = 0; $i -lt $args.Count; $i++) {
        $a = [string]$args[$i]
        if ($a -like '--resume=*') { $id = $a.Substring(9) }
        elseif ($a -eq '--resume' -or $a -eq '-r') {
            # Lookahead: a following non-flag token is the session id; another
            # flag or nothing after it means the flag is bare (no id given).
            if ($i + 1 -lt $args.Count -and -not ([string]$args[$i + 1]).StartsWith('-')) {
                $id = [string]$args[$i + 1]
                $i++
            } else {
                $bare = $true
            }
        }
    }
    if ($bare -and -not $id) {
        # Bare resume flag with no session id: pick the session (and engine) interactively.
        $passArgs = @()
        if ($args.Count -gt 0) { $passArgs = @($args | ForEach-Object { [string]$_ }) }
        & powershell -NoProfile -ExecutionPolicy Bypass -File $resumePickerPs1 @passArgs
        return
    }
    if ($id -and $id -match '^[0-9a-fA-F-]{36}$') {
        # $env:HOME mirrors the bash twin; PowerShell's automatic $HOME ignores it.
        $homeDir = $HOME
        if ($env:HOME) { $homeDir = $env:HOME }
        $dirs = @("$homeDir\.claude", "$homeDir\.claude-lumo\config")
        if ($env:CLAUDE_CONFIG_DIR) { $dirs = @($env:CLAUDE_CONFIG_DIR) + $dirs }
        foreach ($d in ($dirs | Select-Object -Unique)) {
            $t = Get-ChildItem -Path "$d\projects\*\$id.jsonl" -ErrorAction SilentlyContinue | Select-Object -First 1
            if ($t -and (Select-String -Path $t.FullName -SimpleMatch '"model":"lumo-' -List -Quiet)) {
                & claude-lumo @args
                return
            }
        }
    }
    $exe = (Get-Command claude -CommandType Application -ErrorAction Stop | Select-Object -First 1).Source
    & $exe @args
}
