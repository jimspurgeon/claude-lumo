# resume-shim.sh - Resume-aware launcher for claude-lumo (bash and zsh)
# Source this file from your shell profile to enable it (see "Resume shim" in the README).
#
# Purpose: a tool (like Orca) resumes sessions with a plain `claude --resume <id>`. When the
# resumed session's transcript used a lumo-* model, re-launch it through claude-lumo with the
# same arguments; otherwise run the real claude binary unchanged (same args, exit code, output).
# Bare `claude -r` / `claude --resume` (no id) opens the resume-picker helper instead, so the
# engine is picked before Claude Code's own (too-late-to-reroute) session picker runs.
# Do not edit this file: it belongs to the claude-lumo repo and updates overwrite it.
#
# Transcript search order (first hit wins; the id lives under projects/<munged-path>/):
#   1. $CLAUDE_CONFIG_DIR if set
#   2. ~/.claude (shared mode)
#   3. ~/.claude-lumo/config (the separated Lumo data store, when data separation is on)
#
# The function is NOT exported, so claude-lumo.sh (which calls `claude` inside its own bash
# process) keeps reaching the real claude binary: no recursion, no interference.

# Resolve the picker helper next to this shim (~/.claude/lumo is a junction to the repo, so
# sourcing ~/.claude/lumo/scripts/resume-shim.sh finds the repo's picker after updates).
_resume_picker_sh="$(dirname "${BASH_SOURCE[0]}")/resume-picker.sh"

claude() {
    local id="" bare=0 t d
    # Walk over "$@" positionally (no array subscripts: zsh arrays are 1-based and
    # zsh's `argv` is special, so subscripted bash arrays are not portable across
    # both shells). After "--" the remaining tokens are positional arguments, not
    # options, so a later literal -r/--resume must not trigger the picker.
    local prev_resume=0 endopts=0 a
    for a in "$@"; do
        if [ "$endopts" = "1" ]; then
            prev_resume=0
            continue
        fi
        case "$a" in
            --) endopts=1; [ "$prev_resume" = "1" ] && bare=1; prev_resume=0;;
            -r|--resume)
                [ "$prev_resume" = "1" ] && bare=1
                prev_resume=1
                ;;
            --resume=*) id="${a#--resume=}"; prev_resume=0;;
            -*) [ "$prev_resume" = "1" ] && bare=1; prev_resume=0;;
            *)
                # Lookahead: a non-flag token right after a bare -r/--resume is
                # the session id; any other token clears the pending-flag state.
                [ "$prev_resume" = "1" ] && id="$a"
                prev_resume=0
                ;;
        esac
    done
    # A bare -r/--resume still pending at end-of-args means no id was given either.
    [ "$prev_resume" = "1" ] && bare=1
    if [ "$bare" = "1" ] && [ -z "$id" ]; then
        # Bare resume flag with no session id: pick the session (and engine) interactively.
        bash "$_resume_picker_sh" "$@"
        return $?
    fi
    if [ -n "$id" ] && [[ "$id" =~ ^[0-9a-fA-F-]{36}$ ]]; then
        local dirs=("$HOME/.claude" "$HOME/.claude-lumo/config")
        [ -n "$CLAUDE_CONFIG_DIR" ] && dirs=("$CLAUDE_CONFIG_DIR" "${dirs[@]}")
        for d in "${dirs[@]}"; do
            for t in "$d"/projects/*/"$id.jsonl"; do
                [ -f "$t" ] || continue
                if grep -qF '"model":"lumo-' "$t" 2>/dev/null; then
                    command claude-lumo "$@"
                    return $?
                fi
            done
        done
    fi
    command claude "$@"
    return $?
}
